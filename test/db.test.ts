const postgres = process.env.ARCHIPEL_TEST_POSTGRES;

test("SQLite's SQL is said the way PostgreSQL understands it", () => {
  assert.equal(
    toPostgres("SELECT * FROM messages WHERE channel_id=? AND seq<? ORDER BY seq DESC LIMIT ?"),
    "SELECT * FROM messages WHERE channel_id=$1 AND seq<$2 ORDER BY seq DESC LIMIT $3",
  );
  // What is quoted is left alone, question marks and all.
  assert.equal(
    toPostgres("UPDATE users SET display_name='Who? -- me; it''s MAX(a,b)' WHERE id=?"),
    "UPDATE users SET display_name='Who? -- me; it''s MAX(a,b)' WHERE id=$1",
  );
  assert.equal(
    toPostgres("INSERT OR IGNORE INTO topics(id,title) VALUES(?,?)"),
    "INSERT INTO topics(id,title) VALUES($1,$2) ON CONFLICT DO NOTHING",
  );
  assert.equal(
    toPostgres("INSERT OR IGNORE INTO messages(id) VALUES(?) RETURNING messages.channel_id"),
    "INSERT INTO messages(id) VALUES($1) ON CONFLICT DO NOTHING RETURNING messages.channel_id",
  );
  assert.throws(() => toPostgres("INSERT OR REPLACE INTO federation_blocks VALUES(?,?)"), /name the conflict/);
  assert.equal(
    toPostgres("SELECT COALESCE(MAX(seq),0) AS n, MAX(seq,?) AS top, MIN(a, b) FROM t"),
    "SELECT COALESCE(MAX(seq),0) AS n, GREATEST(seq,$1) AS top, LEAST(a, b) FROM t",
  );
  assert.equal(
    toPostgres("SELECT 1 FROM d WHERE (? IS NULL OR d.recipient=?) AND (? LIKE ? AND id=?)"),
    "SELECT 1 FROM d WHERE ($1::text IS NULL OR d.recipient=$2) AND ($3::text LIKE $4 AND id=$5)",
  );
  assert.equal(
    toPostgres("SELECT json_extract(o.activity,'$.object.id') AS id FROM o WHERE instr(body,'/media/')>0"),
    "SELECT ((o.activity)::jsonb #>> '{object,id}') AS id FROM o WHERE strpos(body,'/media/')>0",
  );
  assert.equal(
    toPostgres("SELECT emoji FROM message_reactions WHERE message_id IN () ORDER BY created_at,rowid"),
    "SELECT emoji FROM message_reactions WHERE message_id IN (SELECT NULL WHERE FALSE) ORDER BY created_at,ctid",
  );
  // A migration: its tables in PostgreSQL's types, its comments gone, its version recorded.
  assert.equal(
    toPostgres(`-- A table's comment; with a semicolon
      CREATE TABLE things (
        seq INTEGER PRIMARY KEY AUTOINCREMENT,
        name TEXT NOT NULL UNIQUE COLLATE NOCASE,  -- as people's names are
        owner_id TEXT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
        image BLOB, size INTEGER NOT NULL DEFAULT 0
      );
      PRAGMA foreign_keys=ON;
      PRAGMA user_version=20;`).replace(/\s+/g, " ").trim(),
    'CREATE TABLE things ( seq BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name CITEXT COLLATE "C" NOT NULL UNIQUE, ' +
      'owner_id TEXT COLLATE "C" NOT NULL REFERENCES users(id) ON DELETE CASCADE DEFERRABLE, image BYTEA, size BIGINT NOT NULL DEFAULT 0 ); ' +
      "UPDATE archipel_schema SET version=20",
  );
});

test("changes are reported once committed, with the rows of watched tables, and never when undone", () => {
  const db = new SqliteDatabase(":memory:");
  db.migrate();
  const told: { table: string; rows: Record<string, unknown>[] }[][] = [];
  db.onChange = (changes) => told.push(changes);
  db.prepare("INSERT INTO users(id,username,display_name,created_at) VALUES('u','someone','Someone','now')").run();
  assert.deepEqual(told.splice(0), [[{ table: "users", rows: [] }]]);
  db.transaction(() => {
    db.prepare("INSERT INTO read_marks VALUES('u','a',1)").run();
    db.prepare("INSERT INTO read_marks VALUES('u','b',1)").run();
    assert.deepEqual(told, []);
  });
  assert.equal(JSON.stringify(told.splice(0)), JSON.stringify([[
    { table: "read_marks", rows: [{ user_id: "u" }] },
    { table: "read_marks", rows: [{ user_id: "u" }] },
  ]]));
  assert.throws(() => db.transaction(() => {
    db.prepare("DELETE FROM read_marks WHERE user_id='u'").run();
    throw new Error("Undone");
  }), /Undone/);
  assert.equal(db.prepare("UPDATE read_marks SET seq=2 WHERE user_id='nobody'").run().changes, 0);
  assert.equal(db.prepare("SELECT COUNT(*) AS n FROM read_marks").get()!.n, 2);
  assert.deepEqual(told, []);
  // A listener that fails does not fail the write.
  db.onChange = () => { throw new Error("Nobody listening"); };
  assert.equal(db.prepare("DELETE FROM read_marks WHERE user_id='u'").run().changes, 2);
  db.close();
});

test("an instance moves from its SQLite file into PostgreSQL whole, and carries on from there", { skip: postgres ? false : "needs ARCHIPEL_TEST_POSTGRES" }, (t) => {
  const directory = mkdtempSync(join(tmpdir(), "archipel-migrate-")), path = join(directory, "db.sqlite");
  const origin = "https://chat.example";
  // Written through SQLite itself, whatever database the rest of the suite is using.
  const before = new SqliteDatabase(path), lite = new Store(before, origin);
  const alice = lite.loginIdentity("urn:archipel:development", "alice", "Alice", [], true),
    bob = lite.loginIdentity("urn:archipel:development", "bob", "Bob", []);
  const channel = lite.createChannel(alice, { name: "general", description: "Everything", mode: "threaded", visibility: "public", admission: "open" });
  lite.join(bob, channel.id);
  const first = lite.post(alice, channel.id, { title: "Hello", body: "A thread with ünïcödé and a 'quote'" });
  const reply = lite.post(bob, channel.id, { body: "A reply", parent_id: first.id });
  lite.deleteMessage(bob, reply.id);
  lite.post(bob, channel.id, { body: "Another reply", parent_id: first.id });
  lite.react(bob, first.id, { emoji: "tada", on: true });
  lite.sendDirect(alice, bob.id, "Between us");
  const image = randomBytes(70000);
  before.prepare("INSERT INTO attachments VALUES('file',?,'blob.bin','application/octet-stream',?,?,'2026-01-01T00:00:00.000Z')").run(alice.id, image.length, image);
  const expected = {
    messages: lite.messages(bob, channel.id),
    dms: lite.directHistory(bob, `${origin}/actors/users/${alice.id}`),
    overview: lite.overview(bob),
    counter: before.sequence("messages"),
  };

  const schema = `m_${randomBytes(8).toString("hex")}`, target = new PostgresDatabase(postgres!, schema, true);
  t.after(() => { target.close(); rmSync(directory, { recursive: true }); });
  const copied: Record<string, number> = {};
  copyToPostgres(before, target, (table, rows) => { copied[table] = rows; });
  before.close();
  assert.equal(copied.messages, 3);
  assert.equal(copied.users, 2);
  // A second copy into the same database is refused, and changes nothing.
  const again = new SqliteDatabase(path);
  assert.throws(() => copyToPostgres(again, target), /already holds/);
  again.close();

  const moved = new Store(target, origin);
  assert.equal(target.version(), 24);
  assert.deepEqual(moved.messages(moved.user(bob.id), channel.id), expected.messages);
  assert.deepEqual(moved.directHistory(moved.user(bob.id), `${origin}/actors/users/${alice.id}`), expected.dms);
  assert.deepEqual(moved.overview(moved.user(bob.id)), expected.overview);
  assert.deepEqual(Buffer.from(moved.attachmentBytes("file", 0, image.length)), image);
  // Counters go on from where they were, and names still match whatever their case.
  assert.equal(target.sequence("messages"), expected.counter);
  assert.equal(moved.post(moved.user(alice.id), channel.id, { title: "After", body: "Written to PostgreSQL" }).seq, expected.counter + 1);
  assert.equal(target.prepare("SELECT id FROM users WHERE username=?").get("ALICE")?.id, alice.id);
  assert.throws(() => moved.createChannel(moved.user(alice.id), { name: "GENERAL", description: "", mode: "timeline", visibility: "public", admission: "open" }));
});
