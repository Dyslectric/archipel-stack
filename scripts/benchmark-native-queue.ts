// Profile the exact private routing-index SQL in an isolated schema. No HTTP,
// foreground workload or signatures: this diagnoses writes, not user capacity.
import pg from "pg";
import {randomBytes} from "node:crypto";
import {readFileSync,writeFileSync} from "node:fs";
import {performance} from "node:perf_hooks";
import {resolve} from "node:path";

const url=process.env.ARCHIPEL_TEST_POSTGRES;
if(!url)throw new Error("Requires ARCHIPEL_TEST_POSTGRES pointing to an isolated test database with pg_stat_statements preloaded.");
const schema=`queue_write_${randomBytes(8).toString("hex")}`,db=new pg.Client({connectionString:url});
const sql=readFileSync(resolve("native/src/queue_heads.rs"),"utf8").match(/const SQL: &str = r#"([\s\S]*)"#;/)?.[1];
if(!sql)throw new Error("Could not find current native routing-index SQL.");
await db.connect();
try{
  await db.query("CREATE EXTENSION IF NOT EXISTS pg_stat_statements");
  await db.query(`CREATE SCHEMA "${schema}"; SET search_path TO "${schema}",public`);
  await db.query(`CREATE TABLE federation_outgoing(id TEXT PRIMARY KEY,activity TEXT NOT NULL,signer TEXT NOT NULL,user_id TEXT,channel_id TEXT,purpose TEXT NOT NULL,created_at BIGINT NOT NULL);
    CREATE TABLE federation_deliveries(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,activity_id TEXT NOT NULL REFERENCES federation_outgoing(id),recipient TEXT NOT NULL,
      attempts BIGINT NOT NULL DEFAULT 0,next_attempt BIGINT NOT NULL DEFAULT 0,status TEXT NOT NULL DEFAULT 'pending',error TEXT,UNIQUE(activity_id,recipient));
    CREATE INDEX federation_delivery_due ON federation_deliveries(status,next_attempt);
    CREATE INDEX federation_delivery_order ON federation_deliveries(recipient,status,id);
    CREATE INDEX federation_pending_order ON federation_deliveries(id) WHERE status='pending';
    CREATE INDEX federation_pending_recipient ON federation_deliveries(recipient,id) WHERE status='pending';
    CREATE INDEX federation_pending_activity ON federation_deliveries(activity_id,id) WHERE status='pending';
    CREATE INDEX federation_outgoing_channel ON federation_outgoing(channel_id,id)`);
  await db.query("BEGIN");await db.query(sql);await db.query("COMMIT");
  await db.query(`INSERT INTO federation_outgoing SELECT 'out-'||n,'{}','urn:probe',NULL,'room-'||(n%96),'relay',0 FROM generate_series(1,9600) n`);
  await db.query(`INSERT INTO federation_deliveries(activity_id,recipient) SELECT 'out-'||n,'urn:peer:'||(n%96)||':'||peer FROM generate_series(1,9600) n CROSS JOIN generate_series(1,5) peer`);
  for(const table of ["federation_outgoing","federation_deliveries","native_federation_pending","native_federation_heads"])await db.query(`ANALYZE ${table}`);
  await db.query("SET pg_stat_statements.track='all'");
  const stats=async()=> (await db.query(`SELECT userid,dbid,toplevel,queryid::text,query,calls,total_exec_time,shared_blks_hit FROM pg_stat_statements WHERE dbid=(SELECT oid FROM pg_database WHERE datname=current_database())`)).rows;
  const key=(row:Record<string,unknown>)=>`${row.userid}:${row.dbid}:${row.toplevel}:${row.queryid}`;
  const before=new Map((await stats()).map(row=>[key(row),row]));
  const latencies:number[]=[];
  for(let n=1;n<=300;n++){
    const begin=performance.now();
    await db.query("UPDATE federation_deliveries SET status='sent',attempts=attempts+1,error=NULL WHERE activity_id=$1 AND status='pending'",[`out-${n}`]);
    latencies.push(performance.now()-begin);
  }
  latencies.sort((a,b)=>a-b);
  const queries=(await stats()).map(row=>{
    const prior=before.get(key(row)),calls=Number(row.calls)-Number(prior?.calls??0),totalMs=row.total_exec_time-(prior?.total_exec_time??0);
    return {query:row.query,calls,totalMs,meanMs:calls?totalMs/calls:0,sharedHits:Number(row.shared_blks_hit)-Number(prior?.shared_blks_hit??0)};
  }).filter(row=>row.calls>0).sort((a,b)=>b.totalMs-a.totalMs).slice(0,25);
  const mismatch=await db.query(`WITH expected AS(SELECT DISTINCT ON(d.recipient,o.channel_id) d.recipient,native_federation_lane(o.channel_id) AS lane,d.id AS head_id
      FROM federation_deliveries d JOIN federation_outgoing o ON o.id=d.activity_id WHERE d.status='pending' ORDER BY d.recipient,o.channel_id,d.id)
    SELECT * FROM ((SELECT * FROM expected EXCEPT SELECT * FROM native_federation_heads) UNION ALL
      (SELECT * FROM native_federation_heads EXCEPT SELECT * FROM expected)) differences`);
  if(mismatch.rows.length)throw new Error("Routing heads disagree with durable queue.");
  const report={time:new Date().toISOString(),rows:48000,lanes:480,statements:300,rowsPerStatement:5,
    meanMs:latencies.reduce((sum,n)=>sum+n,0)/latencies.length,p95Ms:latencies[Math.ceil(latencies.length*.95)-1],queries,
    limitation:"Single connection with no competing workload, HTTP, signatures or foreground pages. Nested statement totals overlap. This does not establish active-user capacity."};
  writeFileSync(resolve(process.argv[2]??"test-results/native-queue-write-profile.json"),JSON.stringify(report,null,2)+"\n");
  console.log(JSON.stringify({meanMs:report.meanMs,p95Ms:report.p95Ms,queries:queries.map(q=>({calls:q.calls,meanMs:q.meanMs,query:q.query.slice(0,140)}))},null,2));
}finally{
  await db.query("ROLLBACK").catch(()=>{});
  await db.query(`DROP SCHEMA IF EXISTS "${schema}" CASCADE`).catch(()=>{});
  await db.end();
}
