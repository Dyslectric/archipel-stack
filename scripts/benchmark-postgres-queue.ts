// Reproduce saved recipient backlogs to inspect the sender's exact head query.
import pg from "pg";
import {randomBytes} from "node:crypto";
import {readFileSync,writeFileSync} from "node:fs";
import {resolve} from "node:path";
const url=process.env.ARCHIPEL_TEST_POSTGRES;
if(!url)throw new Error("Set ARCHIPEL_TEST_POSTGRES to an isolated test database.");
const directory=resolve(process.argv[2]);
const snapshot=JSON.parse(readFileSync(resolve(directory,"snapshot-0.json"),"utf8")) as {relay:{recipient:string;status:string}[];queues:{purpose:string;status:string;count:number}[]};
const actors=Object.values(JSON.parse(readFileSync(resolve(directory,"setup.json"),"utf8")).actors) as string[];
const schema=`queueplan_${randomBytes(8).toString("hex")}`,db=new pg.Client({connectionString:url});
await db.connect();
try {
  await db.query(`CREATE SCHEMA "${schema}"`);
  await db.query(`CREATE TABLE "${schema}".federation_deliveries(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,recipient TEXT NOT NULL,status TEXT NOT NULL,next_attempt BIGINT NOT NULL DEFAULT 0)`);
  await db.query(`CREATE INDEX federation_delivery_due ON "${schema}".federation_deliveries(status,next_attempt);
    CREATE INDEX federation_delivery_order ON "${schema}".federation_deliveries(recipient,status,id);
    CREATE INDEX federation_pending_order ON "${schema}".federation_deliveries(id) WHERE status='pending';
    CREATE INDEX federation_pending_recipient ON "${schema}".federation_deliveries(recipient,id) WHERE status='pending'`);
  const rows=[...snapshot.relay];
  const posts=snapshot.queues.filter(q=>q.purpose==="post");
  for(const queue of posts)for(let n=0;n<queue.count;n++)rows.push({recipient:actors[n%actors.length],status:queue.status});
  for(let at=0;at<rows.length;at+=1000) {
    const chunk=rows.slice(at,at+1000);
    await db.query(`INSERT INTO "${schema}".federation_deliveries(recipient,status) SELECT * FROM unnest($1::text[],$2::text[])`,[chunk.map(r=>r.recipient),chunk.map(r=>r.status)]);
  }
  await db.query(`ANALYZE "${schema}".federation_deliveries`);
  const sample=(await db.query(`SELECT id FROM "${schema}".federation_deliveries WHERE status='pending' ORDER BY id LIMIT 40`)).rows.map(r=>String(r.id));
  const query=`SELECT d.id,d.recipient FROM "${schema}".federation_deliveries d WHERE d.status='pending' AND d.next_attempt<=$1 AND d.id!=ALL($2::bigint[])
    AND NOT EXISTS(SELECT 1 FROM "${schema}".federation_deliveries earlier WHERE earlier.recipient=d.recipient AND earlier.id<d.id AND earlier.status='pending') ORDER BY d.id LIMIT 1`;
  const explain=async()=> (await db.query(`EXPLAIN (ANALYZE,BUFFERS) ${query}`,[Date.now(),sample])).rows.map(r=>r["QUERY PLAN"]).join("\n");
  const before=await explain();
  await db.query(`CREATE INDEX federation_pending_id ON "${schema}".federation_deliveries(id) WHERE status='pending'`);
  const indexed=await explain();
  const lateral=`SELECT d.id,d.recipient FROM "${schema}".federation_deliveries d WHERE d.status='pending' AND d.next_attempt<=$1 AND d.id!=ALL($2::bigint[])
    AND d.id=(SELECT earlier.id FROM "${schema}".federation_deliveries earlier WHERE earlier.recipient=d.recipient AND earlier.status='pending' ORDER BY earlier.id LIMIT 1) ORDER BY d.id LIMIT 1`;
  const scalar=(await db.query(`EXPLAIN (ANALYZE,BUFFERS) ${lateral}`,[Date.now(),sample])).rows.map(r=>r["QUERY PLAN"]).join("\n");
  const report={source:directory,rows:rows.length,before,indexed,scalar,
    limitation:"Recreated recipients/statuses and head-relevant indexes; excludes original IDs, actor discovery, transport and foreground request load. The additional id index duplicates migration 28's existing index and is diagnostic only."};
  writeFileSync(resolve(directory,"postgres-queue-plan.json"),JSON.stringify(report,null,2)+"\n");console.log(JSON.stringify(report,null,2));
} finally {await db.query(`DROP SCHEMA "${schema}" CASCADE`).catch(()=>{});await db.end();}
