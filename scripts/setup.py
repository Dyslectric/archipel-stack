def parse_raw_env(source):
    """Compose's raw env_file format: everything after '=' is literal."""
    result = {}
    for line in source.split("\n"):
        line = line.rstrip("\r")
        if not line or line.startswith("#") or "=" not in line:
            continue
        key, value = line.split("=", 1)
        if key:
            result[key] = value
    return result


def parse_env(source):
    """Read our Compose dotenv files, including the previous Node setup format.

    Values are data, never shell commands. Generated double-quoted values escape
    dollar signs for Compose; unescape those when loading the prompt defaults.
    """
    generated = source.startswith(HEADER)
    result = {}
    for number, line in enumerate(source.split("\n"), 1):
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        match = re.fullmatch(r"(?:export\s+)?([A-Z_][A-Z0-9_]*)\s*=\s*(.*)", line)
        if not match:
            raise ValueError(f"Invalid environment entry on line {number}")
        key, value = match.groups()
        if value.startswith(("'", '"', "`")):
            quote = value[0]
            # Prior generated files never escaped the chosen quote delimiter.
            end = 1
            while end < len(value):
                if value[end] == quote:
                    break
                if generated and value[end] == "\\":
                    end += 1
                end += 1
            if end >= len(value) or (value[end + 1:].strip() and not value[end + 1:].strip().startswith("#")):
                raise ValueError(f"Invalid quoted environment value on line {number}")
            if generated and quote == '"':
                try:
                    value = json.loads(value[:end + 1]).replace("$$", "$")
                except ValueError:
                    raise ValueError(f"Invalid quoted environment value on line {number}") from None
            else:
                value = value[1:end]
        else:
            value = re.split(r"\s+#", value, maxsplit=1)[0].rstrip()
        result[key] = value
    return result


def serialize_env(settings):
    lines = []
    for key, value in settings.items():
        if not re.fullmatch(r"[A-Z_][A-Z0-9_]*", key) or not isinstance(value, str) or re.search(r"[\x00-\x08\x0a-\x1f\x7f]", value):
            raise ValueError(f"Invalid single-line environment value for {key}")
        # Compose double quotes support JSON's quote/backslash escapes. '$$'
        # prevents substitutions even in custom variables and admin subjects.
        encoded = json.dumps(value.replace("$", "$$"), ensure_ascii=False)
        lines.append(f"{key}={encoded}")
    return HEADER + "\n".join(lines) + "\n"


def parse_trusted_proxies(value=""):
    if not value.strip():
        return []
    addresses = [entry.strip() for entry in value.split(",")]
    for address in addresses:
        parts = address.split("/")
        try:
            ip = ipaddress.ip_address(parts[0])
        except ValueError:
            raise ValueError("TRUSTED_PROXY must contain IP addresses or CIDRs separated by commas") from None
        if len(parts) > 2 or "%" in parts[0]:
            raise ValueError("Invalid TRUSTED_PROXY address")
        if len(parts) == 2 and (not re.fullmatch(r"[0-9]+", parts[1]) or not 1 <= int(parts[1]) <= ip.max_prefixlen):
            raise ValueError("TRUSTED_PROXY CIDR prefixes must be 1–32 for IPv4 or 1–128 for IPv6")
    return list(dict.fromkeys(addresses))


def checked_url(value, key, origin=False):
    try:
        if re.search(r"[\s\\]", value):
            raise ValueError()
        parsed = urlsplit(value)
        host = parsed.hostname
        port = parsed.port  # Validate the port even if it isn't needed later.
        if not host or parsed.username is not None or parsed.password is not None or parsed.query or parsed.fragment:
            raise ValueError()
        if port is not None and not 1 <= port <= 65535:
            raise ValueError()
        if origin and parsed.path not in ("", "/"):
            raise ValueError()
        if parsed.scheme != "https" and not (origin and parsed.scheme == "http" and host in ("localhost", "127.0.0.1", "::1")):
            raise ValueError()
        if any(char in value for char in "?#"):
            raise ValueError()
    except (ValueError, TypeError):
        requirement = "an HTTPS origin (loopback HTTP is allowed)" if origin else "an HTTPS URL without credentials, query, or fragment"
        raise ValueError(f"{key} must be {requirement}") from None
    return parsed


def port_in_use(port):
    """Whether another service on this machine already listens on a TCP port."""
    with socket.socket(socket.AF_INET, socket.SOCK_STREAM) as probe:
        try:
            probe.bind(("0.0.0.0", port))
        except OSError:
            return True
    return False


def free_port(start, in_use):
    """The first port from start that is free here, so instances sharing a machine differ."""
    for port in range(start, min(start + 100, 65536)):
        if not in_use(port):
            return port
    return start


def parse_credentials(value):
    """DNS provider credentials as NAME=value pairs separated by whitespace."""
    pairs = {}
    for entry in value.split():
        name, separator, secret = entry.partition("=")
        if not separator or not re.fullmatch(r"[A-Z_][A-Z0-9_]*", name) or not secret or name.startswith("LEGO_"):
            raise ValueError("XMPP_ACME_DNS_CREDENTIALS must be NAME=value pairs separated by spaces")
        pairs[name] = secret
    return pairs


def xmpp_dns_records(settings):
    """The SRV records that make this instance reachable by clients and other servers."""
    domain, target = settings["XMPP_DOMAIN"], settings.get("XMPP_SRV_TARGET") or settings["XMPP_DOMAIN"]
    client, server = settings.get("XMPP_CLIENT_PORT") or "5222", settings.get("XMPP_SERVER_PORT") or "5269"
    return [
        f"_xmpp-client._tcp.{domain}. SRV 0 5 {client} {target}.",
        f"_xmpp-server._tcp.{domain}. SRV 0 5 {server} {target}.",
        f"_xmpp-server._tcp.channels.{domain}. SRV 0 5 {server} {target}.",
    ]


def project_name(value):
    """Compose's own normalisation of a directory name into a project name."""
    return re.sub(r"[^a-z0-9_-]", "", value.lower()).lstrip("_-")


def validate_setup(settings):
    mode = settings.get("SETUP_MODE")
    if not re.fullmatch(r"[a-z0-9][a-z0-9_-]*", settings.get("COMPOSE_PROJECT_NAME", "")):
        raise ValueError("COMPOSE_PROJECT_NAME must use lowercase letters, digits, dashes and underscores")
    if mode not in MODES:
        raise ValueError("Choose container, proxy, or traefik mode")
    port = settings.get("PORT", "")
    if not re.fullmatch(r"[0-9]+", port) or not 1 <= int(port) <= 65535:
        raise ValueError("Invalid PORT")
    base = checked_url(settings.get("BASE_URL", ""), "BASE_URL", origin=True)
    if settings.get("HOST") != "0.0.0.0" or settings.get("DEV_AUTH") != "false":
        raise ValueError("Container deployments require HOST=0.0.0.0 and DEV_AUTH=false")
    if settings.get("REGISTRATION_MODE") not in ("open", "invite_only"):
        raise ValueError("REGISTRATION_MODE must be open or invite_only")
    issuer, client = settings.get("OIDC_ISSUER", ""), settings.get("OIDC_CLIENT_ID", "")
    if bool(issuer) != bool(client):
        raise ValueError("Set both OIDC_ISSUER and OIDC_CLIENT_ID")
    if issuer:
        checked_url(issuer, "OIDC_ISSUER")
    method = settings.get("OIDC_AUTH_METHOD")
    if method not in ("none", "client_secret_basic", "client_secret_post"):
        raise ValueError("Invalid OIDC_AUTH_METHOD")
    if method != "none" and not settings.get("OIDC_CLIENT_SECRET"):
        raise ValueError("OIDC_CLIENT_SECRET is required")
    parse_trusted_proxies(settings.get("TRUSTED_PROXY", ""))
    if settings.get("DATABASE", "sqlite") not in DATABASES:
        raise ValueError("DATABASE must be sqlite or postgres")
    # The password is generated; one supplied by hand has to survive Compose and a connection string.
    if settings.get("DATABASE") == "postgres" and not re.fullmatch(r"[A-Za-z0-9_-]{16,128}", settings.get("POSTGRES_PASSWORD", "")):
        raise ValueError("POSTGRES_PASSWORD must be 16 to 128 letters, digits, dashes or underscores")
    # Empty keeps the application's default.
    for key, low, high in (
        ("RATE_LIMIT_API", 1, 100000), ("RATE_LIMIT_AUTH", 1, 100000), ("RATE_LIMIT_MEDIA", 1, 100000),
        ("RATE_LIMIT_FEDERATION", 1, 100000), ("FEDERATION_SEND_RATE", 1, 1000), ("FEDERATION_PEER_SEND_RATE", 0, 100000),
        ("FEDERATION_SEND_INTERVAL", 100, 600000),
    ):
        value = settings.get(key, "")
        if value and (not re.fullmatch(r"[0-9]{1,6}", value) or not low <= int(value) <= high):
            raise ValueError(f"{key} must be an integer between {low} and {high}")
    domain = settings.get("XMPP_DOMAIN", "")
    for key, default in (("XMPP_CLIENT_PORT", "5222"), ("XMPP_SERVER_PORT", "5269")):
        value = settings.get(key) or default
        if not re.fullmatch(r"[0-9]{1,5}", value) or not 1 <= int(value) <= 65535:
            raise ValueError(f"{key} must be an integer between 1 and 65535")
    if domain:
        if int(settings.get("XMPP_CLIENT_PORT") or "5222") == int(settings.get("XMPP_SERVER_PORT") or "5269"):
            raise ValueError("XMPP client and server ports must differ")
        if len(domain) > 253 or not re.fullmatch(HOSTNAME, domain) or any(not part or len(part) > 63 or part.startswith("-") or part.endswith("-") for part in domain.split(".")):
            raise ValueError("XMPP_DOMAIN must be a lowercase DNS hostname")
        if not re.fullmatch(r"[A-Za-z0-9_-]{43,128}", settings.get("XMPP_BRIDGE_SECRET", "")):
            raise ValueError("XMPP_BRIDGE_SECRET must be a random base64url secret of at least 43 characters")
        try:
            ipaddress.ip_address(settings.get("XMPP_BIND_ADDRESS", "0.0.0.0"))
        except ValueError:
            raise ValueError("XMPP_BIND_ADDRESS must be an IP address") from None
        target = settings.get("XMPP_SRV_TARGET") or domain
        if len(target) > 253 or not re.fullmatch(HOSTNAME, target) or re.fullmatch(r"[0-9.]+", target):
            raise ValueError("XMPP_SRV_TARGET must be a lowercase DNS hostname, not an IP address")
        source = settings.get("XMPP_CERT_SOURCE") or "manual"
        if source not in CERT_SOURCES:
            raise ValueError("XMPP_CERT_SOURCE must be manual, acme, or traefik")
        if source == "acme":
            if not re.fullmatch(r"[^@\s]+@[^@\s]+", settings.get("XMPP_ACME_EMAIL", "")):
                raise ValueError("XMPP_ACME_EMAIL must be the address the certificate authority may contact")
            if settings.get("XMPP_ACME_ACCEPT_TOS") != "true":
                raise ValueError("ACME certificates require agreeing to the certificate authority's terms of service (XMPP_ACME_ACCEPT_TOS=true)")
            challenge = settings.get("XMPP_ACME_CHALLENGE")
            if challenge not in ("dns", "http"):
                raise ValueError("XMPP_ACME_CHALLENGE must be dns or http")
            if challenge == "http" and mode == "proxy":
                raise ValueError("XMPP_ACME_CHALLENGE=http requires container mode for direct port 80 access or traefik mode to route challenges through the proxy; choose dns for other proxies")
            if challenge == "http" and mode == "traefik" and not re.fullmatch(r"[a-zA-Z0-9_.-]+", settings.get("XMPP_ACME_HTTP_ENTRYPOINT", "")):
                raise ValueError("Invalid XMPP_ACME_HTTP_ENTRYPOINT")
            if challenge == "dns" and not re.fullmatch(r"[a-z0-9-]+", settings.get("XMPP_ACME_DNS_PROVIDER", "")):
                raise ValueError("XMPP_ACME_DNS_PROVIDER must be a lego DNS provider code, such as cloudflare")
            parse_credentials(settings.get("XMPP_ACME_DNS_CREDENTIALS", ""))
        if source == "traefik":
            if mode != "traefik" or not settings.get("TRAEFIK_CERT_RESOLVER"):
                raise ValueError("Traefik certificates for XMPP require Traefik mode with a certificate resolver")
            if not re.fullmatch(r"/[^\s:\\]*", settings.get("XMPP_TRAEFIK_ACME_DIR", "")) or not re.fullmatch(r"[A-Za-z0-9._-]+", settings.get("XMPP_TRAEFIK_ACME_NAME", "")):
                raise ValueError("Give the absolute host path of Traefik's acme.json, without spaces or colons")
    if mode in ("proxy", "traefik"):
        if base.scheme != "https":
            raise ValueError("Proxy deployments require an HTTPS BASE_URL")
        if not settings.get("TRUSTED_PROXY", "").strip():
            raise ValueError("Set the actual proxy peer IP or CIDR in TRUSTED_PROXY")
    network = settings.get("PROXY_NETWORK", "")
    if network and not re.fullmatch(r"[A-Za-z0-9][A-Za-z0-9_.-]*", network):
        raise ValueError("Invalid external Docker network name")
    if mode == "traefik":
        if not network:
            raise ValueError("Traefik mode requires an external Docker network")
        if not re.fullmatch(r"[a-zA-Z0-9.-]+", settings.get("TRAEFIK_HOST", "")):
            raise ValueError("Traefik routing requires a DNS hostname or IPv4 address")
        for key in ("TRAEFIK_ENTRYPOINT", "TRAEFIK_CERT_RESOLVER"):
            value = settings.get(key, "")
            if (key == "TRAEFIK_ENTRYPOINT" or value) and not re.fullmatch(r"[a-zA-Z0-9_.-]+", value):
                raise ValueError(f"Invalid {key}")
    # Validate every preserved custom variable before writing either file.
    serialize_env(settings)


def collect_setup(previous, ask, requested_mode=None, in_use=lambda port: False):
    default_mode = previous.get("SETUP_MODE") or "container"
    if default_mode == "local":
        default_mode = "container"
    mode = requested_mode or ask("Deployment mode (container / proxy / traefik)", default_mode)
    if mode == "local":
        mode = "container"
    if mode not in MODES:
        raise ValueError("Unknown deployment mode")
    proxy = mode in ("proxy", "traefik")
    # Names this instance's containers, volumes and Traefik routers. Changing it later
    # starts from new, empty volumes, so an existing deployment keeps what it has.
    instance = ask("Instance name (unique per instance on this machine)", previous.get("COMPOSE_PROJECT_NAME") or "archipel")
    port = ask("Host port (used only for loopback publishing)", previous.get("PORT") or "8788")
    base_default = previous.get("BASE_URL")
    if not base_default or (proxy and not base_default.startswith("https:")):
        base_default = "https://chat.example.org" if proxy else f"http://127.0.0.1:{port}"
    base_url = ask("Public base URL", base_default)
    base = checked_url(base_url, "BASE_URL", origin=True)
    network, trusted = "", ""
    if proxy:
        external = "yes" if mode == "traefik" else ask("Use an existing external Docker proxy network? (yes / no)", "yes")
        if external not in ("yes", "no"):
            raise ValueError("Choose yes or no for the external network")
        if external == "yes":
            network = ask("Existing external Docker network name", previous.get("PROXY_NETWORK") or "proxy")
        trusted = ask("Trusted proxy peer IP or CIDR (comma-separated for several)", previous.get("TRUSTED_PROXY") or "")
    issuer = ask("OIDC issuer URL (empty configures login later)", previous.get("OIDC_ISSUER") or "")
    client_id = ask("OIDC client ID", previous.get("OIDC_CLIENT_ID") or "") if issuer else ""
    method = ask("OIDC authentication method (none / client_secret_basic / client_secret_post)", previous.get("OIDC_AUTH_METHOD") or "none") if issuer else "none"
    secret = "" if method == "none" else ask("OIDC client secret", previous.get("OIDC_CLIENT_SECRET") or "", True)
    admins = ask("Administrator OIDC subjects (comma-separated; may be set after first sign-in)", previous.get("ADMIN_SUBJECTS") or "")
    entrypoint = ask("Existing Traefik HTTPS entrypoint", previous.get("TRAEFIK_ENTRYPOINT") or "websecure") if mode == "traefik" else "websecure"
    resolver = ask("Existing Traefik certificate resolver (empty uses configured certificates)", previous.get("TRAEFIK_CERT_RESOLVER") or "") if mode == "traefik" else ""
    files = ["compose.yaml", "compose.proxy.yaml" if network else "compose.local.yaml"]
    database = ask("Database (sqlite keeps one file in the data volume / postgres runs PostgreSQL beside the application)", previous.get("DATABASE") or "sqlite")
    if database not in DATABASES:
        raise ValueError("Choose sqlite or postgres for the database")
    if database == "postgres":
        files.append("compose.postgres.yaml")
    xmpp_domain = ask("XMPP account domain (empty disables Prosody)", previous.get("XMPP_DOMAIN") or "")
    xmpp_client_port = previous.get("XMPP_CLIENT_PORT") or "5222"
    xmpp_server_port = previous.get("XMPP_SERVER_PORT") or "5269"
    xmpp = {key: previous.get(key, "") for key in XMPP_SETUP_KEYS}
    if xmpp_domain:
        # A second instance on this machine is offered the next free pair of ports.
        if not previous.get("XMPP_CLIENT_PORT"):
            xmpp_client_port = str(free_port(5222, in_use))
        xmpp_client_port = ask("XMPP client STARTTLS port", xmpp_client_port)
        if not previous.get("XMPP_SERVER_PORT"):
            xmpp_server_port = str(free_port(5269, in_use))
        xmpp_server_port = ask("XMPP federation port", xmpp_server_port)
        files.append("compose.xmpp.yaml")
        xmpp["XMPP_SRV_TARGET"] = ask("DNS name of this machine for XMPP SRV records (DNS-only, not behind a web proxy or CDN)", xmpp["XMPP_SRV_TARGET"] or xmpp_domain)
        source = ask("XMPP certificates (manual / acme / traefik)", xmpp["XMPP_CERT_SOURCE"] or "manual")
        xmpp["XMPP_CERT_SOURCE"] = source
        if source == "acme":
            xmpp["XMPP_ACME_EMAIL"] = ask("Contact email for the certificate authority", xmpp["XMPP_ACME_EMAIL"])
            agreed = ask("Agree to the certificate authority's terms of service? (yes / no)", "yes" if xmpp["XMPP_ACME_ACCEPT_TOS"] == "true" else "no")
            xmpp["XMPP_ACME_ACCEPT_TOS"] = "true" if agreed == "yes" else "false"
            challenge = ask("ACME challenge (dns / http; http uses Traefik's HTTP entrypoint in traefik mode, otherwise host port 80)", xmpp["XMPP_ACME_CHALLENGE"] or "dns")
            xmpp["XMPP_ACME_CHALLENGE"] = challenge
            if challenge == "dns":
                xmpp["XMPP_ACME_DNS_PROVIDER"] = ask("DNS provider code for lego (for example cloudflare)", xmpp["XMPP_ACME_DNS_PROVIDER"])
                xmpp["XMPP_ACME_DNS_CREDENTIALS"] = ask("DNS provider credentials as NAME=value, separated by spaces", xmpp["XMPP_ACME_DNS_CREDENTIALS"], True)
            else:
                xmpp["XMPP_ACME_DNS_PROVIDER"] = xmpp["XMPP_ACME_DNS_CREDENTIALS"] = ""
            files.append("compose.xmpp-acme.yaml")
            if challenge == "http":
                if mode == "traefik":
                    xmpp["XMPP_ACME_HTTP_ENTRYPOINT"] = ask("Existing Traefik HTTP challenge entrypoint", xmpp["XMPP_ACME_HTTP_ENTRYPOINT"] or "web")
                    files.append("compose.xmpp-acme-traefik.yaml")
                else:
                    files.append("compose.xmpp-acme-http.yaml")
        elif source == "traefik":
            store = ask("Host path of Traefik's acme.json", xmpp["XMPP_TRAEFIK_ACME_DIR"].rstrip("/") + "/" + xmpp["XMPP_TRAEFIK_ACME_NAME"] if xmpp["XMPP_TRAEFIK_ACME_NAME"] else "")
            directory, _, xmpp["XMPP_TRAEFIK_ACME_NAME"] = store.rpartition("/")
            xmpp["XMPP_TRAEFIK_ACME_DIR"] = directory or ("/" if store.startswith("/") else "")
    if mode == "traefik":
        files.append("compose.traefik.yaml")
        if resolver:
            files.append("compose.acme.yaml")
        if xmpp_domain and xmpp["XMPP_CERT_SOURCE"] == "traefik":
            files.append("compose.xmpp-traefik-certs.yaml")
    settings = {
        **previous,
        "SETUP_MODE": mode, "PORT": port, "HOST": "0.0.0.0", "DEV_AUTH": "false",
        "BASE_URL": urlunsplit((base.scheme, base.netloc, "", "", "")),
        "DATABASE_PATH": "/app/data/archipel.sqlite", "TRUSTED_PROXY": trusted,
        "OIDC_ISSUER": issuer, "OIDC_CLIENT_ID": client_id,
        "OIDC_AUTH_METHOD": method, "OIDC_CLIENT_SECRET": secret,
        "ADMIN_SUBJECTS": admins,
        "REGISTRATION_MODE": ask("Initial instance registration (open / invite_only; admins can change it in the app)", previous.get("REGISTRATION_MODE") or "open"),
        "PROXY_NETWORK": network, "TRAEFIK_HOST": base.hostname,
        "TRAEFIK_ENTRYPOINT": entrypoint, "TRAEFIK_CERT_RESOLVER": resolver,
        "COMPOSE_FILE": os.pathsep.join(files),
        "COMPOSE_PROJECT_NAME": instance,
        "DATABASE": database,
        "POSTGRES_PASSWORD": (previous.get("POSTGRES_PASSWORD") or secrets.token_urlsafe(32)) if database == "postgres" else "",
        "XMPP_DOMAIN": xmpp_domain,
        "XMPP_BRIDGE_SECRET": (previous.get("XMPP_BRIDGE_SECRET") or secrets.token_urlsafe(32)) if xmpp_domain else "",
        "XMPP_BIND_ADDRESS": previous.get("XMPP_BIND_ADDRESS") or "0.0.0.0",
        "XMPP_CLIENT_PORT": xmpp_client_port,
        "XMPP_SERVER_PORT": xmpp_server_port,
        "XMPP_CERTS_PATH": previous.get("XMPP_CERTS_PATH") or "./data/xmpp-certs",
        **xmpp,
        # Compose reads this one; it follows the chosen challenge.
        "XMPP_ACME_HTTP": "true" if xmpp["XMPP_ACME_CHALLENGE"] == "http" else "false",
    }
    validate_setup(settings)
    return settings


def write_setup(directory, settings):
    validate_setup(settings)
    directory = Path(directory).resolve()
    if not directory.is_dir():
        raise ValueError("The setup directory must already exist")
    files = {
        ".env": serialize_env({**settings, "OIDC_CLIENT_SECRET": "", "XMPP_BRIDGE_SECRET": "", "XMPP_ACME_DNS_CREDENTIALS": "", "POSTGRES_PASSWORD": ""}),
        ".env.container": "# Literal container credentials; read by Compose using format: raw.\nOIDC_CLIENT_SECRET=" + settings["OIDC_CLIENT_SECRET"] + "\nXMPP_BRIDGE_SECRET=" + settings.get("XMPP_BRIDGE_SECRET", "") + "\n",
    }
    if settings.get("XMPP_DOMAIN") and settings.get("XMPP_CERT_SOURCE") == "acme":
        credentials = parse_credentials(settings.get("XMPP_ACME_DNS_CREDENTIALS", ""))
        files[".env.acme"] = "# Literal DNS provider credentials for the certificate client; format: raw.\n" + "".join(f"{name}={value}\n" for name, value in credentials.items())
    if settings.get("DATABASE") == "postgres":
        # One password under the two names its readers know: the database's own, and the client's.
        files[".env.postgres"] = "# Literal PostgreSQL password for the database and the application; format: raw.\nPOSTGRES_PASSWORD=" + settings["POSTGRES_PASSWORD"] + "\nPGPASSWORD=" + settings["POSTGRES_PASSWORD"] + "\n"
    backups = []
    for name, data in files.items():
        path = directory / name
        if path.exists():
            backup = directory / f"{name}.backup.{time.time_ns()}.{uuid.uuid4()}"
            fd = os.open(backup, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
            with os.fdopen(fd, "wb") as output, path.open("rb") as original:
                shutil.copyfileobj(original, output)
            backups.append(backup)
        fd, temporary = tempfile.mkstemp(prefix=f"{name}.tmp.", dir=directory)
        try:
            with os.fdopen(fd, "w", encoding="utf-8", newline="\n") as output:
                output.write(data)
                output.flush()
                os.fsync(output.fileno())
            os.replace(temporary, path)
            path.chmod(0o600)
        finally:
            if os.path.exists(temporary):
                os.unlink(temporary)
    return {"files": [directory / name for name in files], "backups": backups}


def prompt(label, value, secret=False):
    if secret:
        answer = getpass.getpass(f"{label} (hidden{'; Enter keeps current' if value else ''}; - clears): ")
    else:
        answer = input(f"{label}{' [' + value + ']' if value else ''} (- clears): ").strip()
    return "" if answer == "-" else answer or value


def main(argv=None):
    parser = argparse.ArgumentParser(description="Configure Archipel with Python only; setup does not start containers or change proxy networks.")
    parser.add_argument("--mode", choices=(*MODES, "local"), help="Deployment mode; local is an alias for loopback container deployment")
    parser.add_argument("--non-interactive", action="store_true", help="Use existing configuration and supplied environment variables")
    parser.add_argument("--directory", type=Path, default=Path(__file__).resolve().parent.parent, help="Existing configuration directory (defaults to the project root)")
    options = parser.parse_args(argv)
    directory = options.directory.resolve()
    if not directory.is_dir():
        raise ValueError("The setup directory must already exist")
    env_path, raw_path = directory / ".env", directory / ".env.container"
    previous = parse_env(env_path.read_text(encoding="utf-8")) if env_path.exists() else {}
    if previous.get("SETUP_MODE") != "local" and raw_path.exists():
        previous["OIDC_CLIENT_SECRET"] = parse_raw_env(raw_path.read_text(encoding="utf-8")).get("OIDC_CLIENT_SECRET", "")
        previous["XMPP_BRIDGE_SECRET"] = parse_raw_env(raw_path.read_text(encoding="utf-8")).get("XMPP_BRIDGE_SECRET", "")
    acme_path = directory / ".env.acme"
    if acme_path.exists():
        previous["XMPP_ACME_DNS_CREDENTIALS"] = " ".join(f"{name}={value}" for name, value in parse_raw_env(acme_path.read_text(encoding="utf-8")).items())
    postgres_path = directory / ".env.postgres"
    if postgres_path.exists():
        previous["POSTGRES_PASSWORD"] = parse_raw_env(postgres_path.read_text(encoding="utf-8")).get("POSTGRES_PASSWORD", "")
    # Compose's default, so configuring an existing deployment keeps its volumes.
    previous.setdefault("COMPOSE_PROJECT_NAME", project_name(directory.name) or "archipel")
    for key in (*APP_KEYS, *XMPP_SETUP_KEYS, "COMPOSE_PROJECT_NAME", "SETUP_MODE", "PROXY_NETWORK", "TRAEFIK_ENTRYPOINT", "TRAEFIK_CERT_RESOLVER", "DATABASE", "POSTGRES_PASSWORD"):
        if key in os.environ:
            previous[key] = os.environ[key]
    if not options.non_interactive and not sys.stdin.isatty():
        raise ValueError("Interactive setup requires a terminal. Use --non-interactive with environment variables instead.")
    ask = (lambda _label, value, secret=False: value) if options.non_interactive else prompt
    settings = collect_setup(previous, ask, options.mode, port_in_use)
    result = write_setup(directory, settings)
    print(f"\nWrote {' and '.join(path.name for path in result['files'])} with private file permissions.")
    if result["backups"]:
        print("Existing configuration was backed up beside the original files.")
    print(f"OIDC callback: {settings['BASE_URL']}/auth/callback")
    if not settings["OIDC_ISSUER"]:
        print("Configure an OIDC issuer and client before users can sign in.")
    if settings["PROXY_NETWORK"]:
        print(f"The proxy must already be attached to Docker network: {settings['PROXY_NETWORK']}")
    if settings["XMPP_DOMAIN"]:
        domain, target = settings["XMPP_DOMAIN"], settings["XMPP_SRV_TARGET"]
        source = settings["XMPP_CERT_SOURCE"]
        if source == "acme":
            print(f"Certificates for {domain} and channels.{domain} are requested when the stack starts; follow them with: docker compose logs -f xmpp-acme")
            if settings["XMPP_ACME_CHALLENGE"] == "http":
                if settings["SETUP_MODE"] == "traefik":
                    print(f"HTTP challenges are routed through Traefik's {settings['XMPP_ACME_HTTP_ENTRYPOINT']} entrypoint to lego; no extra host port is published.")
                    print(f"If Traefik redirects HTTP to HTTPS or handles its own HTTP challenges, enable --entryPoints.{settings['XMPP_ACME_HTTP_ENTRYPOINT']}.allowACMEByPass=true in Traefik's static configuration. See docs/xmpp.md.")
                    print("Both names must reach this Traefik on public port 80 for the HTTP challenge.")
                else:
                    print("Both names must resolve to this machine, with port 80 reachable, for the HTTP challenge.")
        elif source == "traefik":
            print(f"Traefik's resolver {settings['TRAEFIK_CERT_RESOLVER']} must be able to issue {domain} and channels.{domain}; Prosody reads them from {settings['XMPP_TRAEFIK_ACME_DIR'].rstrip('/')}/{settings['XMPP_TRAEFIK_ACME_NAME']}.")
        else:
            print(f"Prosody requires readable certificates in {settings['XMPP_CERTS_PATH']} for {domain} and channels.{domain} before starting.")
        print("\nPublish these DNS records so XMPP clients and other servers can find this instance:")
        for record in xmpp_dns_records(settings):
            print(f"  {record}")
        print(f"{target} needs an A/AAAA record that points straight at this machine: a proxied CDN record does not carry XMPP.")
        print(f"Allow inbound TCP {settings['XMPP_CLIENT_PORT']} (clients) and {settings['XMPP_SERVER_PORT']} (federation).")
        print(f"Check a record with: dig +short SRV _xmpp-server._tcp.{domain}   See docs/xmpp.md.")
    if settings["DATABASE"] == "postgres":
        print("PostgreSQL runs beside the application and keeps its data in the archipel-postgres volume.")
        print("To bring over an instance that ran on SQLite, before starting: docker compose build && docker compose run --rm archipel node scripts/migrate-postgres.js")
    print("Validate with: docker compose config --quiet\nStart with: docker compose up --build -d")
    return 0


